const withFallback = (overrides: Partial<Record<keyof typeof en, string>>) => ({
  ...en,
  ...overrides,
});

export const translations: Record<AppLanguage, Record<string, string>> = {
  en: { ...en },
  "zh-HK": withFallback(zhHKOverrides),
  kz: withFallback(kzOverrides),
  ru: withFallback(ruOverrides),
};

const validateCoverage = () => {
  const englishKeys = Object.keys(en);
  for (const language of Object.keys(translations) as AppLanguage[]) {
    const map = translations[language] ?? {};
    const missing = englishKeys.filter((key) => !(key in map));
    if (missing.length > 0) {
      throw new Error(
        `Missing translation keys for ${language}: ${missing.slice(0, 20).join(", ")}`
      );
    }
  }
};

validateCoverage();

export function tForLanguage(language: AppLanguage, key: TranslationKey, fallback?: string) {
  return translations[language]?.[key] ?? fallback ?? translations.en[key] ?? key;
}
